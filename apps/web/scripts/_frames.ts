import { writeFileSync } from "node:fs";
import { renderCreature, idleFrames } from "../src/game/pixel/creature";
import { toRgba } from "../src/game/pixel/pixels";
import { encodePng } from "./png";
const [out, id, eraArg] = process.argv.slice(2);
const era = Number(eraArg);
const n = idleFrames(id);
const sprites = Array.from({ length: n }, (_, frame) => renderCreature(id, { era, frame }).pixels);
const S = 3, cw = sprites[0].w + 4, ch = sprites[0].h + 4;
const W = cw * Math.min(n, 4) * S, H = ch * Math.ceil(n / 4) * S;
const data = new Uint8Array(W * H * 4);
for (let i = 0; i < W * H; i++) data.set([38, 46, 72, 255], i * 4);
sprites.forEach((px, k) => { const rgba = toRgba(px); const c = k % 4, r = Math.floor(k / 4);
  for (let y = 0; y < px.h * S; y++) for (let x = 0; x < px.w * S; x++) { const f = (Math.floor(y / S) * px.w + Math.floor(x / S)) * 4; if (rgba.data[f + 3] < 128) continue; data.set([rgba.data[f], rgba.data[f+1], rgba.data[f+2], 255], ((r*ch*S+y)*W + c*cw*S + x)*4); } });
writeFileSync(out, encodePng({ width: W, height: H, data })); console.log(n, "frames");
